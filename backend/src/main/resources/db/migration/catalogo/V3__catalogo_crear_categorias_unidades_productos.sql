CREATE TABLE catalogo.producto (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(30)    NOT NULL,
    descripcion         VARCHAR(500)   NOT NULL,
    categoria_id        BIGINT         NOT NULL,
    unidad_medida       VARCHAR(5)     NOT NULL,
    tipo_afectacion_igv VARCHAR(2)     NOT NULL,
    precio_venta        NUMERIC(12, 2) NOT NULL,
    precio_compra       NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stock               NUMERIC(12, 3) NOT NULL DEFAULT 0,
    creado_en           TIMESTAMPTZ    NOT NULL,
    creado_por          VARCHAR(50),
    actualizado_en      TIMESTAMPTZ    NOT NULL,
    actualizado_por     VARCHAR(50),
    CONSTRAINT uk_producto_codigo UNIQUE (codigo),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES catalogo.categoria (id),
    CONSTRAINT fk_producto_unidad FOREIGN KEY (unidad_medida) REFERENCES catalogo.unidad_medida (codigo),
    CONSTRAINT ck_producto_afectacion CHECK (tipo_afectacion_igv IN
        ('10', '11', '12', '13', '14', '15', '16', '17', '20', '21', '30', '31', '32', '33', '34', '35', '36', '40')),
    CONSTRAINT ck_producto_precio_venta CHECK (precio_venta > 0),
    CONSTRAINT ck_producto_precio_compra CHECK (precio_compra >= 0)
);

CREATE INDEX ix_producto_categoria ON catalogo.producto (categoria_id);
CREATE INDEX ix_producto_descripcion ON catalogo.producto (lower(descripcion));
